package dwg

// HeaderDXFVar maps a DXF HEADER variable to its source.
//
// Field names a HeaderVars field. When Field is empty, Special says where the value comes from:
//   - "flags:M" / "nflags:M": (Flags & M) shifted down to bit 0, "nflags" inverted (§9 Flags BL)
//   - "acadver", "acadmaintver", "codepage": file header; "lastsavedby": AcDb:SummaryInfo
//   - "measurement": AcDb:Template
//   - "local:F": field F (stored in universal time, = $TDU...) converted to local time
//
// Handle fields are written as the referenced record name, except for group codes 5 and 3xx,
// which take the hex handle. CmColor fields write DXFIndex(). JulianDate fields write Float().
// R2004 files lack the R2007+ variables; use HeaderDefaults() values for them.
type HeaderDXFVar struct {
	Name    string
	Codes   []int
	Field   string
	Special string
}

